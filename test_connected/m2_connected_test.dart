// Explicit opt-in SDK/backend test; not a replacement for Android UI E2E.
// Run with config generated by scripts/prepare-m2-local.ps1 on a disposable local stack.
void main() {
  final config = AppConfig.fromEnvironment();
  const emailA = String.fromEnvironment('TEST_EMAIL_A');
  const emailB = String.fromEnvironment('TEST_EMAIL_B');
  const password = String.fromEnvironment('TEST_PASSWORD');
  test(
    'real Auth/API: owner-scoped push/pull, restart, edits, tombstones and RLS',
    () async {
      expect(
        config.connected &&
            emailA.isNotEmpty &&
            emailB.isNotEmpty &&
            password.isNotEmpty,
        isTrue,
        reason:
            'Provide local connected test config; this test never silently skips.',
      );
      final a = SupabaseClient(config.supabaseUrl, config.supabaseAnonKey);
      final b = SupabaseClient(config.supabaseUrl, config.supabaseAnonKey);
      final directory = await Directory.systemTemp.createTemp(
        'bunly-connected-',
      );
      final file = File('${directory.path}/test.sqlite');
      var db = AppDatabase(NativeDatabase(file));
      SupabaseLearningRemote? remote;
      AppDatabase? second;
      try {
        await Authenticate(SupabaseAuthRepository(a))(emailA, password);
        await Authenticate(SupabaseAuthRepository(b))(emailB, password);
        final owner = a.auth.currentUser!.id;
        final grammar = await SupabaseGrammarSource(a).fetch();
        expect(grammar, isNotEmpty);
        final grammarId = grammar.first['id'] as String;
        final repository = LocalLearningRepository(
          db,
          namespace: config.namespace,
          ownerId: owner,
          queueRemote: true,
        );
        final id = const Uuid().v4();
        await SaveNote(repository)(
          Note(
            id: id,
            grammarId: grammarId,
            content: 'M2 connected',
            updatedAt: DateTime.now().toUtc(),
          ),
        );
        await UpdateLearning(repository).saveProfile(
          const UserProfile(displayName: 'M2 local test', dailyMinutes: 30),
        );
        await repository.setSaved(grammarId, true);
        await repository.setStatus(grammarId, LearningStatus.review);
        // No worker has run yet: the local transaction survives database restart.
        await db.close();
        db = AppDatabase(NativeDatabase(file));
        final reopened = LocalLearningRepository(
          db,
          namespace: config.namespace,
          ownerId: owner,
          queueRemote: true,
        );
        expect(
          (await reopened.watchNotes(grammarId).first).single.content,
          'M2 connected',
        );
        remote = SupabaseLearningRemote(
          a,
          url: config.supabaseUrl,
          key: config.supabaseAnonKey,
          ownerId: owner,
        );
        final sync = LearningSync(
          db,
          remote,
          namespace: config.namespace,
          ownerId: owner,
        );
        await sync.run();
        expect(await db.select(db.syncOutbox).get(), isEmpty);
        expect(
          (await a.from('notes').select().eq('id', id)).single['content'],
          'M2 connected',
        );
        expect(await b.from('notes').select().eq('id', id), isEmpty);
        await expectLater(
          b.from('notes').insert({
            'id': '40000000-0000-0000-0000-000000000002',
            'user_id': owner,
            'grammar_id': grammarId,
            'content': 'spoof',
          }),
          throwsA(isA<PostgrestException>()),
        );
        expect(
          await b
              .from('notes')
              .update({'content': 'hacked'})
              .eq('id', id)
              .select(),
          isEmpty,
        );
        expect(
          (await a.from('notes').select().eq('id', id)).single['content'],
          'M2 connected',
        );
        second = AppDatabase(NativeDatabase.memory());
        await LearningSync(
          second,
          remote,
          namespace: config.namespace,
          ownerId: owner,
        ).run();
        final downloaded = LocalLearningRepository(
          second,
          namespace: config.namespace,
          ownerId: owner,
          queueRemote: true,
        );
        expect(
          (await downloaded.watchNotes(grammarId).first).single.content,
          'M2 connected',
        );
        expect(
          (await downloaded.watchSummary().first).saved,
          contains(grammarId),
        );
        expect(
          (await downloaded.watchSummary().first).statusOf(grammarId),
          LearningStatus.review,
        );
        expect((await downloaded.watchProfile().first).dailyMinutes, 30);
        await SaveNote(reopened)(
          Note(
            id: id,
            grammarId: grammarId,
            content: 'edited',
            updatedAt: DateTime.now().toUtc(),
          ),
        );
        await sync.run();
        expect(
          (await a.from('notes').select().eq('id', id)).single['content'],
          'edited',
        );
        await reopened.deleteNote(id);
        await reopened.setSaved(grammarId, false);
        await sync.run();
        expect(
          (await a.from('notes').select().eq('id', id)).single['deleted_at'],
          isNotNull,
        );
        expect(await reopened.watchNotes(grammarId).first, isEmpty);
        await a.auth.signOut();
        await expectLater(sync.run(), throwsStateError);
      } finally {
        await second?.close();
        await remote?.dispose();
        await db.close();
        await a.dispose();
        await b.dispose();
        await directory.delete(recursive: true);
      }
    },
  );

  test('real Auth/API: baseline revision sync, quota RPC, and practice RLS', () async {
    expect(
      config.connected &&
          emailA.isNotEmpty &&
          emailB.isNotEmpty &&
          password.isNotEmpty,
      isTrue,
      reason:
          'Provide local connected test config; this test never silently skips.',
    );
    final anon = SupabaseClient(config.supabaseUrl, config.supabaseAnonKey);
    final a = SupabaseClient(config.supabaseUrl, config.supabaseAnonKey);
    final b = SupabaseClient(config.supabaseUrl, config.supabaseAnonKey);
    try {
      await Authenticate(SupabaseAuthRepository(a))(emailA, password);
      await Authenticate(SupabaseAuthRepository(b))(emailB, password);
      final ownerA = a.auth.currentUser!.id;
      final grammar = await SupabaseGrammarSource(a).fetch();
      expect(grammar, isNotEmpty);
      final grammarId = grammar.first['id'] as String;

      // Read-only question bank & server-derived review states reject client writes.
      await expectLater(
        a.from('practice_questions').insert({
          'grammar_id': grammarId,
          'question_type': 'cloze',
          'prompt': 'test',
          'accepted_answers': ['a'],
          'explanation_vi': 'test',
        }),
        throwsA(isA<PostgrestException>()),
      );
      await expectLater(
        a.from('review_states').insert({
          'user_id': ownerA,
          'grammar_id': grammarId,
          'stage': 4,
          'due_at': DateTime.now().toUtc().toIso8601String(),
        }),
        throwsA(isA<PostgrestException>()),
      );
      expect(await a.from('practice_questions').select(), isA<List<dynamic>>());
      expect(await a.from('review_states').select(), isA<List<dynamic>>());

      // Safe quota inspection works for authenticated users and fails closed for anon.
      await expectLater(
        anon.rpc('bunly_my_analysis_quota'),
        throwsA(isA<PostgrestException>()),
      );
      final quota = Map<String, dynamic>.from(
        await a.rpc('bunly_my_analysis_quota') as Map,
      );
      expect(quota['has_entitlement'], isA<bool>());
      expect(quota['remaining_quota'], isA<int>());
      expect(DateTime.parse(quota['reset_at_utc'] as String).isUtc, isTrue);

      // Multi-device monotonic revision, idempotent replay, conflict detection, and cross-user isolation.
      final noteId = const Uuid().v4();
      final op1 = const Uuid().v4();
      final created = Map<String, dynamic>.from(
        await a.rpc(
              'bunly_sync_personal_record',
              params: {
                'p_operation_id': op1,
                'p_entity_table': 'notes',
                'p_record_id': noteId,
                'p_base_revision': 0,
                'p_delete': false,
                'p_payload': {'grammar_id': grammarId, 'content': 'Sync rev 1'},
              },
            )
            as Map,
      );
      expect(created['status'], 'applied');
      expect(created['revision'], 1);

      final replay = Map<String, dynamic>.from(
        await a.rpc(
              'bunly_sync_personal_record',
              params: {
                'p_operation_id': op1,
                'p_entity_table': 'notes',
                'p_record_id': noteId,
                'p_base_revision': 0,
                'p_delete': false,
                'p_payload': {'grammar_id': grammarId, 'content': 'Sync rev 1'},
              },
            )
            as Map,
      );
      expect(replay['status'], 'duplicate_ack');
      expect(replay['revision'], 1);

      final conflict = Map<String, dynamic>.from(
        await a.rpc(
              'bunly_sync_personal_record',
              params: {
                'p_operation_id': const Uuid().v4(),
                'p_entity_table': 'notes',
                'p_record_id': noteId,
                'p_base_revision': 0,
                'p_delete': false,
                'p_payload': {
                  'grammar_id': grammarId,
                  'content': 'Stale overwrite',
                },
              },
            )
            as Map,
      );
      expect(conflict['status'], 'conflict');
      expect(conflict['current_revision'], 1);
      expect((conflict['server_record'] as Map)['content'], 'Sync rev 1');

      final updated = Map<String, dynamic>.from(
        await a.rpc(
              'bunly_sync_personal_record',
              params: {
                'p_operation_id': const Uuid().v4(),
                'p_entity_table': 'notes',
                'p_record_id': noteId,
                'p_base_revision': 1,
                'p_delete': false,
                'p_payload': {'grammar_id': grammarId, 'content': 'Sync rev 2'},
              },
            )
            as Map,
      );
      expect(updated['status'], 'applied');
      expect(updated['revision'], 2);

      await expectLater(
        b.rpc(
          'bunly_sync_personal_record',
          params: {
            'p_operation_id': const Uuid().v4(),
            'p_entity_table': 'notes',
            'p_record_id': noteId,
            'p_base_revision': 0,
            'p_delete': false,
            'p_payload': {'grammar_id': grammarId, 'content': 'Hijacked note'},
          },
        ),
        throwsA(isA<PostgrestException>()),
      );

      final deleted = Map<String, dynamic>.from(
        await a.rpc(
              'bunly_sync_personal_record',
              params: {
                'p_operation_id': const Uuid().v4(),
                'p_entity_table': 'notes',
                'p_record_id': noteId,
                'p_base_revision': 2,
                'p_delete': true,
                'p_payload': <String, dynamic>{},
              },
            )
            as Map,
      );
      expect(deleted['status'], 'applied');
      expect(deleted['revision'], 3);
      expect((deleted['record'] as Map)['deleted_at'], isNotNull);
    } finally {
      await anon.dispose();
      await a.dispose();
      await b.dispose();
    }
  });

  test(
    'real Auth/API: SupabaseGrammarAnalysisRepository & PracticeSync fail-closed & clean pull',
    () async {
      expect(
        config.connected && emailA.isNotEmpty && password.isNotEmpty,
        isTrue,
        reason:
            'Provide local connected test config; this test never silently skips.',
      );
      final anon = SupabaseClient(config.supabaseUrl, config.supabaseAnonKey);
      final a = SupabaseClient(config.supabaseUrl, config.supabaseAnonKey);
      final db = AppDatabase(NativeDatabase.memory());
      SupabasePracticeRemote? remote;
      try {
        final anonAnalysis = SupabaseGrammarAnalysisRepository(anon);
        await expectLater(
          anonAnalysis.loadQuota(),
          throwsA(
            isA<AnalysisException>().having(
              (e) => e.kind,
              'kind',
              AnalysisFailureKind.unauthenticated,
            ),
          ),
        );

        await Authenticate(SupabaseAuthRepository(a))(emailA, password);
        final ownerA = a.auth.currentUser!.id;
        final analysisRepo = SupabaseGrammarAnalysisRepository(a);
        final quota = await analysisRepo.loadQuota();
        expect(quota.hasEntitlement, isA<bool>());
        expect(quota.dailyLimit, greaterThanOrEqualTo(0));
        expect(quota.resetAtUtc.isUtc, isTrue);

        // With GEMINI_FREE_TIER_CONFIRMED=false locally, analyze-grammar must fail closed (503 unavailable).
        final reqId = const Uuid().v4();
        await expectLater(
          analysisRepo.analyze(
            requestId: reqId,
            normalizedText: '日本へ行ったことがある。',
          ),
          throwsA(
            isA<AnalysisException>()
                .having((e) => e.kind, 'kind', AnalysisFailureKind.unavailable)
                .having((e) => e.retryable, 'retryable', isTrue),
          ),
        );

        // PracticeSync pulls question bank, attempts, and review_states without failing on empty question bank.
        final storage = LocalPracticeStorageRepository(
          db,
          namespace: config.namespace,
          ownerId: ownerA,
          queueRemote: true,
        );
        remote = SupabasePracticeRemote(
          a,
          url: config.supabaseUrl,
          key: config.supabaseAnonKey,
          ownerId: ownerA,
        );
        final practiceSync = PracticeSync(
          db,
          remote,
          storage,
          namespace: config.namespace,
          ownerId: ownerA,
        );
        await practiceSync.run();
        expect(await db.select(db.syncOutbox).get(), isEmpty);
        expect(
          await storage.loadCachedQuestions(),
          hasLength(greaterThanOrEqualTo(180)),
        );
      } finally {
        await remote?.dispose();
        await db.close();
        await anon.dispose();
        await a.dispose();
      }
    },
  );
}
