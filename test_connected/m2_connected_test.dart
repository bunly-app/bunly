import 'dart:io';
import 'package:uuid/uuid.dart';
import 'package:bunly/app/config.dart';
import 'package:bunly/core/database/app_database.dart';
import 'package:bunly/features/auth/data/auth_repositories.dart';
import 'package:bunly/features/auth/domain/authenticate.dart';
import 'package:bunly/features/grammar/data/grammar_sources.dart';
import 'package:bunly/features/learning/data/learning_sync.dart';
import 'package:bunly/features/learning/data/local_learning_repository.dart';
import 'package:bunly/features/learning/domain/note.dart';
import 'package:bunly/features/learning/domain/personal_repository.dart';
import 'package:bunly/features/learning/domain/save_note.dart';
import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:supabase_flutter/supabase_flutter.dart';

// Explicit opt-in SDK/backend test; not a replacement for Android UI E2E.
// Run with config generated by scripts/prepare-m2-local.ps1 on a disposable local stack.
void main() {
  final config = AppConfig.fromEnvironment();
  const emailA = String.fromEnvironment('TEST_EMAIL_A');
  const emailB = String.fromEnvironment('TEST_EMAIL_B');
  const password = String.fromEnvironment('TEST_PASSWORD');
  test(
    'real Auth/API: owner-scoped push/pull, restart, edits, tombstones and RLS',
    () async {
      expect(
        config.connected &&
            emailA.isNotEmpty &&
            emailB.isNotEmpty &&
            password.isNotEmpty,
        isTrue,
        reason:
            'Provide local connected test config; this test never silently skips.',
      );
      final a = SupabaseClient(config.supabaseUrl, config.supabaseAnonKey);
      final b = SupabaseClient(config.supabaseUrl, config.supabaseAnonKey);
      final directory = await Directory.systemTemp.createTemp(
        'bunly-connected-',
      );
      final file = File('${directory.path}/test.sqlite');
      var db = AppDatabase(NativeDatabase(file));
      SupabaseLearningRemote? remote;
      AppDatabase? second;
      try {
        await Authenticate(SupabaseAuthRepository(a))(emailA, password);
        await Authenticate(SupabaseAuthRepository(b))(emailB, password);
        final owner = a.auth.currentUser!.id;
        final grammar = await SupabaseGrammarSource(a).fetch();
        expect(grammar, isNotEmpty);
        final grammarId = grammar.first['id'] as String;
        final repository = LocalLearningRepository(
          db,
          namespace: config.namespace,
          ownerId: owner,
          queueRemote: true,
        );
        final id = const Uuid().v4();
        await SaveNote(repository)(
          Note(
            id: id,
            grammarId: grammarId,
            content: 'M2 connected',
            updatedAt: DateTime.now().toUtc(),
          ),
        );
        await UpdateLearning(repository).saveProfile(
          const UserProfile(displayName: 'M2 local test', dailyMinutes: 30),
        );
        await repository.setSaved(grammarId, true);
        await repository.setStatus(grammarId, LearningStatus.review);
        // No worker has run yet: the local transaction survives database restart.
        await db.close();
        db = AppDatabase(NativeDatabase(file));
        final reopened = LocalLearningRepository(
          db,
          namespace: config.namespace,
          ownerId: owner,
          queueRemote: true,
        );
        expect(
          (await reopened.watchNotes(grammarId).first).single.content,
          'M2 connected',
        );
        remote = SupabaseLearningRemote(
          a,
          url: config.supabaseUrl,
          key: config.supabaseAnonKey,
          ownerId: owner,
        );
        final sync = LearningSync(
          db,
          remote,
          namespace: config.namespace,
          ownerId: owner,
        );
        await sync.run();
        expect(await db.select(db.syncOutbox).get(), isEmpty);
        expect(
          (await a.from('notes').select().eq('id', id)).single['content'],
          'M2 connected',
        );
        expect(await b.from('notes').select().eq('id', id), isEmpty);
        await expectLater(
          b.from('notes').insert({
            'id': '40000000-0000-0000-0000-000000000002',
            'user_id': owner,
            'grammar_id': grammarId,
            'content': 'spoof',
          }),
          throwsA(isA<PostgrestException>()),
        );
        expect(
          await b
              .from('notes')
              .update({'content': 'hacked'})
              .eq('id', id)
              .select(),
          isEmpty,
        );
        expect(
          (await a.from('notes').select().eq('id', id)).single['content'],
          'M2 connected',
        );
        second = AppDatabase(NativeDatabase.memory());
        await LearningSync(
          second,
          remote,
          namespace: config.namespace,
          ownerId: owner,
        ).run();
        final downloaded = LocalLearningRepository(
          second,
          namespace: config.namespace,
          ownerId: owner,
          queueRemote: true,
        );
        expect(
          (await downloaded.watchNotes(grammarId).first).single.content,
          'M2 connected',
        );
        expect(
          (await downloaded.watchSummary().first).saved,
          contains(grammarId),
        );
        expect(
          (await downloaded.watchSummary().first).statusOf(grammarId),
          LearningStatus.review,
        );
        expect((await downloaded.watchProfile().first).dailyMinutes, 30);
        await SaveNote(reopened)(
          Note(
            id: id,
            grammarId: grammarId,
            content: 'edited',
            updatedAt: DateTime.now().toUtc(),
          ),
        );
        await sync.run();
        expect(
          (await a.from('notes').select().eq('id', id)).single['content'],
          'edited',
        );
        await reopened.deleteNote(id);
        await reopened.setSaved(grammarId, false);
        await sync.run();
        expect(
          (await a.from('notes').select().eq('id', id)).single['deleted_at'],
          isNotNull,
        );
        expect(await reopened.watchNotes(grammarId).first, isEmpty);
        await a.auth.signOut();
        await expectLater(sync.run(), throwsStateError);
      } finally {
        await second?.close();
        await remote?.dispose();
        await db.close();
        await a.dispose();
        await b.dispose();
        await directory.delete(recursive: true);
      }
    },
  );
}
